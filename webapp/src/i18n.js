// translator returns t(key, ...args): %s placeholders are filled in order.
export function translator(locale) {
    const strings = STRINGS[(locale || '').split('-')[0]] || STRINGS.en;
    return (key, ...args) => {
        let i = 0;
        return (strings[key] ?? STRINGS.en[key] ?? key).replace(/%s/g, () => String(args[i++] ?? ''));
    };
}
